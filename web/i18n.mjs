export const locales = {
  en: 'English',
  'zh-CN': '简体中文',
  'zh-TW': '繁體中文',
  id: 'Bahasa Indonesia',
  ja: '日本語',
  ko: '한국어',
};
export const languageStorageKey = 'rumable.setup.language';

function matchLocale(language) {
  if (typeof language !== 'string') return null;
  const parts = language.toLowerCase().split('-');
  if (parts[0] === 'zh') {
    if (parts.includes('hant')) return 'zh-TW';
    if (parts.includes('hans')) return 'zh-CN';
    return parts.some(part => ['tw', 'hk', 'mo'].includes(part)) ? 'zh-TW' : 'zh-CN';
  }
  return Object.hasOwn(locales, parts[0]) ? parts[0] : null;
}

export function resolveLocale(preference, languages = []) {
  if (Object.hasOwn(locales, preference)) return preference;
  for (const language of languages) {
    const locale = matchLocale(language);
    if (locale) return locale;
  }
  return 'en';
}

// Accept a provider so even accessing window.localStorage can fail safely.
export function readLanguagePreference(storage) {
  try {
    const saved = storage()?.getItem(languageStorageKey);
    return Object.hasOwn(locales, saved) ? saved : null;
  } catch { return null; }
}

export function saveLanguagePreference(storage, locale) {
  try {
    if (Object.hasOwn(locales, locale)) storage()?.setItem(languageStorageKey, locale);
  } catch { /* Language switching still works when storage is blocked. */ }
}

export function createTranslator(locale = 'en') {
  const catalog = Object.hasOwn(locales, locale) ? catalogs[locale] : null;
  return function t(key, values = {}) {
    return (catalog?.[key] ?? messages[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => {
      const value = values[name];
      return value?.key ? t(value.key, value.values) : value ?? match;
    });
  };
}

export class SetupError extends Error {
  constructor(key, values = {}) {
    super(createTranslator()(key, values));
    this.name = 'SetupError';
    this.key = key;
    this.values = values;
  }
}

export function errorMessage(error, t, fallback = 'error.config') {
  return error instanceof SetupError ? t(error.key, error.values) : t(fallback);
}

export function translatePage(root, t) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const attribute of ['placeholder', 'aria-label']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
}
